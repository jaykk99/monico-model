# ─── Tokenizer ────────────────────────────────────────────────────────────────

class MonicoTokenizer:
    """Train a BPE tokenizer on the Monico corpus."""

    def __init__(self, vocab_size: int = 128_000):
        self.vocab_size = vocab_size

    def train(self, files: List[str], output_dir: str):
        """Train tokenizer using HuggingFace tokenizers library."""
        from tokenizers import ByteLevelBPETokenizer

        tokenizer = ByteLevelBPETokenizer()
        tokenizer.train(
            files=files,
            vocab_size=self.vocab_size,
            min_frequency=2,
            special_tokens=[
                "<|pad|>", "<|bos|>", "<|eos|>", "<|unk|>",
                "[MONICO]", "[RESPONSE]", "[CODE]", "[SECURITY]",
                "[CRYPTO]", "[DEVOPS]", "[AUTOMATION]", "[ANALYSIS]",
                "[CTF WRITEUP]", "[SOLIDITY CONTRACT]",
                "<|system|>", "<|user|>", "<|assistant|>",
            ]
        )
        Path(output_dir).mkdir(parents=True, exist_ok=True)
        tokenizer.save_model(output_dir)
        log.info(f"Tokenizer saved to {output_dir}")
        return tokenizer

    def tokenize_files(self, input_files: List[str], output_dir: str,
                        tokenizer_path: str, seq_len: int = 4096):
        """Tokenize text files to binary format for training."""
        from tokenizers import Tokenizer

        tok = Tokenizer.from_file(tokenizer_path)
        Path(output_dir).mkdir(parents=True, exist_ok=True)

        for fpath in input_files:
            out_path = Path(output_dir) / (Path(fpath).stem + ".bin")
            log.info(f"Tokenizing {fpath} -> {out_path}")

            all_ids = []
            with open(fpath, "r", errors="replace") as f:
                for line in f:
                    if line.strip():
                        enc = tok.encode(line)
                        all_ids.extend(enc.ids)
                        all_ids.append(2)  # EOS between documents

            arr = np.array(all_ids, dtype=np.uint32)
            arr.tofile(out_path)
            log.info(f"  Written {len(arr):,} tokens ({out_path.stat().st_size/1e6:.1f}MB)")


# ─── HuggingFace Dataset Downloader ──────────────────────────────────────────

def download_hf_datasets(output_dir: str, hf_token: str = ""):
    """Download key datasets from HuggingFace Hub."""
    datasets_to_fetch = [
        # (dataset_id, split, text_column, max_samples)
        ("bigcode/the-stack-v2-dedup", "train", "content", 5_000_000),
        ("togethercomputer/RedPajama-Data-1T-Sample", "train", "text", 2_000_000),
        ("codeparrot/codeparrot-clean", "train", "content", 1_000_000),
    ]

    try:
        from datasets import load_dataset
    except ImportError:
        log.error("pip install datasets first")
        return

    Path(output_dir).mkdir(parents=True, exist_ok=True)

    for ds_id, split, col, max_samples in datasets_to_fetch:
        name = ds_id.split("/")[-1]
        out_path = Path(output_dir) / f"{name}.jsonl"
        if out_path.exists():
            log.info(f"Skipping {ds_id} (already downloaded)")
            continue

        log.info(f"Downloading {ds_id} ...")
        try:
            ds = load_dataset(ds_id, split=split, streaming=True,
                              token=hf_token if hf_token else None)
            with open(out_path, "w") as f:
                for i, example in enumerate(ds):
                    if i >= max_samples:
                        break
                    text = example.get(col, "")
                    if quality_filter(text):
                        f.write(json.dumps({"text": text}) + "\n")
            log.info(f"  Saved {out_path}")
        except Exception as e:
            log.error(f"  Failed: {e}")


# ─── Main Pipeline ─────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--stage", choices=["download", "tokenize_train", "tokenize", "all"], default="all")
    parser.add_argument("--data_dir", default="data/raw")
    parser.add_argument("--output_dir", default="data/tokenized")
    parser.add_argument("--tokenizer_dir", default="tokenizer")
    parser.add_argument("--seq_len", type=int, default=4096)
    parser.add_argument("--hf_token", default=os.environ.get("HF_TOKEN", ""))
    args = parser.parse_args()

    if args.stage in ("download", "all"):
        download_hf_datasets(args.data_dir, args.hf_token)

    if args.stage in ("tokenize_train", "all"):
        tok = MonicoTokenizer(vocab_size=128_000)
        raw_files = list(Path(args.data_dir).glob("*.jsonl"))[:10]  # Use first 10 files for tokenizer training
        text_files = []
        for f in raw_files:
            # Convert jsonl to plain text for tokenizer training
            txt_path = str(f).replace(".jsonl", ".txt")
            with open(f) as fin, open(txt_path, "w") as fout:
                for line in fin:
                    d = json.loads(line)
                    fout.write(d.get("text", "") + "\n")
            text_files.append(txt_path)
        tok.train(text_files, args.tokenizer_dir)

    if args.stage in ("tokenize", "all"):
        tok = MonicoTokenizer()
        tokenizer_file = Path(args.tokenizer_dir) / "tokenizer.json"
        raw_files = [str(f) for f in Path(args.data_dir).glob("*.txt")]
        tok.tokenize_files(raw_files, args.output_dir, str(tokenizer_file), args.seq_len)

    log.info("Pipeline complete!")


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    main()
