# ─── Quality Filters ──────────────────────────────────────────────────────────

def quality_filter(text: str, min_len=50, max_len=100_000) -> bool:
    """Basic quality heuristics — keep good text, discard garbage."""
    if not text or len(text) < min_len or len(text) > max_len:
        return False
    # Too many special characters
    special_ratio = sum(1 for c in text if not c.isalnum() and c not in " \n\t.,;:!?-_()[]{}\"'/\\") / len(text)
    if special_ratio > 0.35:
        return False
    # Repetitive content
    words = text.lower().split()
    if len(words) > 10 and len(set(words)) / len(words) < 0.2:
        return False
    return True


def code_quality_filter(code: str, lang: str = "python") -> bool:
    """Filters for code quality."""
    if not quality_filter(code, min_len=20):
        return False
    lines = code.split("\n")
    non_empty = [l for l in lines if l.strip()]
    if len(non_empty) < 3:
        return False
    # Reject auto-generated boilerplate
    boilerplate_patterns = [
        r"DO NOT EDIT", r"GENERATED BY", r"AUTO-GENERATED",
        r"Lorem ipsum", r"test test test",
    ]
    for pat in boilerplate_patterns:
        if re.search(pat, code, re.IGNORECASE):
            return False
    return True


# ─── Deduplication ────────────────────────────────────────────────────────────

class MinHashDeduplicator:
    """MinHash LSH for near-duplicate detection."""

    def __init__(self, threshold=0.85, num_perm=128):
        self.threshold = threshold
        self.num_perm = num_perm
        self.seen_hashes = set()
        try:
            from datasketch import MinHash, MinHashLSH
            self.lsh = MinHashLSH(threshold=threshold, num_perm=num_perm)
            self.minhash_cls = MinHash
            self.use_minhash = True
        except ImportError:
            log.warning("datasketch not available — falling back to exact hash dedup")
            self.use_minhash = False

    def _exact_hash(self, text: str) -> str:
        return hashlib.md5(text.lower().strip().encode()).hexdigest()

    def is_duplicate(self, text: str, doc_id: str) -> bool:
        if not self.use_minhash:
            h = self._exact_hash(text)
            if h in self.seen_hashes:
                return True
            self.seen_hashes.add(h)
            return False

        tokens = set(text.lower().split())
        m = self.minhash_cls(num_perm=self.num_perm)
        for t in tokens:
            m.update(t.encode())
        try:
            results = self.lsh.query(m)
            if results:
                return True
            self.lsh.insert(doc_id, m)
            return False
        except Exception:
            return False


# ─── Domain-Specific Processors ──────────────────────────────────────────────

class GitHubCodeProcessor:
    """Process GitHub code repos for The Stack v2 / custom scrapes."""

    LANGS = {
        "python": [".py"],
        "javascript": [".js", ".mjs", ".cjs"],
        "typescript": [".ts", ".tsx"],
        "rust": [".rs"],
        "go": [".go"],
        "c": [".c", ".h"],
        "cpp": [".cpp", ".cc", ".cxx", ".hpp"],
        "solidity": [".sol"],
        "shell": [".sh", ".bash", ".zsh"],
        "dockerfile": ["Dockerfile"],
        "yaml": [".yaml", ".yml"],
        "terraform": [".tf"],
    }

    MAX_FILE_SIZE = 500_000  # 500KB per file

    def process_repo(self, repo_path: Path) -> Iterator[Dict]:
        for lang, exts in self.LANGS.items():
            for ext in exts:
                pattern = f"**/*{ext}" if ext.startswith(".") else f"**/{ext}"
                for file in repo_path.glob(pattern):
                    try:
                        if file.stat().st_size > self.MAX_FILE_SIZE:
                            continue
                        code = file.read_text(errors="replace")
                        if code_quality_filter(code, lang):
                            yield {
                                "text": f"# {lang} | {file.name}\n{code}",
                                "lang": lang,
                                "source": "github",
                                "path": str(file.relative_to(repo_path))
                            }
                    except Exception:
                        pass


class CybersecurityProcessor:
    """Process CTF writeups, CVE descriptions, exploit-db entries."""

    CVE_TEMPLATE = """[SECURITY] CVE-{cve_id}
Severity: {severity}
CVSS: {cvss}
Description: {description}
Affected: {affected}
Vector: {vector}
References: {references}

[ANALYSIS]
{analysis}
"""

    def process_nvd_entry(self, entry: Dict) -> Optional[str]:
        """Process an NVD CVE JSON entry into training text."""
        try:
            cve_id = entry["cve"]["CVE_data_meta"]["ID"]
            desc = entry["cve"]["description"]["description_data"][0]["value"]
            metrics = entry.get("impact", {}).get("baseMetricV3", {})
            cvss = metrics.get("cvssV3", {})

            return self.CVE_TEMPLATE.format(
                cve_id=cve_id,
                severity=cvss.get("baseSeverity", "UNKNOWN"),
                cvss=cvss.get("baseScore", "N/A"),
                description=desc,
                affected=", ".join([
                    node.get("cpe23Uri", "")
                    for config in entry.get("configurations", {}).get("nodes", [])
                    for cpe_match in config.get("cpe_match", [])
                    for node in [cpe_match]
                ])[:200],
                vector=cvss.get("vectorString", ""),
                references=", ".join([
                    r.get("url", "")
                    for r in entry.get("cve", {}).get("references", {}).get("reference_data", [])
                ][:3]),
                analysis=""  # Will be filled by synthetic data gen
            )
        except Exception:
            return None

    def process_ctf_writeup(self, text: str, challenge_name: str = "") -> Optional[str]:
        """Process CTF writeup into training-ready format."""
        if len(text) < 200:
            return None
        header = f"[CTF WRITEUP] {challenge_name}\n[SOLUTION]\n"
        return header + text


class CryptoWeb3Processor:
    """Process Solidity contracts, DeFi docs, protocol specs."""

    SOLIDITY_TEMPLATE = """[SOLIDITY CONTRACT]
// SPDX-License-Identifier: {license}
// Network: {network}
// Purpose: {purpose}

{code}

[CONTRACT ANALYSIS]
{analysis}
"""

    def process_solidity_file(self, code: str, filepath: str = "") -> Optional[str]:
        if not code or len(code) < 50:
            return None
        # Extract license
        license_match = re.search(r"SPDX-License-Identifier:\s*(\S+)", code)
        license_str = license_match.group(1) if license_match else "Unknown"

        return self.SOLIDITY_TEMPLATE.format(
            license=license_str,
            network="Ethereum/EVM",
            purpose="Smart Contract",
            code=code[:8000],
            analysis=""
        )


